#!/usr/bin/env python3
"""Check archived source integrity and relocated files without importing models."""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
import re
import subprocess
import sys
import tokenize
from collections import Counter
from pathlib import Path
from urllib.parse import unquote, urlsplit


def check(root: Path, source: Path | None) -> dict:
    manifest = json.loads((root / "docs/migration-manifest.json").read_text())
    entries = manifest["entries"]
    errors: list[str] = []
    counts: Counter = Counter()
    source_paths = [e["source_path"] for e in entries]
    if len(source_paths) != len(set(source_paths)):
        errors.append("Duplicate source paths in manifest")
    moved_paths: set[str] = set()
    for entry in entries:
        counts[entry["action"]] += 1
        if entry["action"] != "moved_to_ins_cod":
            continue
        rel = entry["destination_path"]
        path = root / rel
        if not path.resolve().is_relative_to(root):
            errors.append(f"Destination escapes repository: {rel}")
            continue
        if rel in moved_paths:
            errors.append(f"Duplicate destination: {rel}")
        moved_paths.add(rel)
        if not path.is_file() or path.is_symlink():
            errors.append(f"Missing regular file: {rel}")
            continue
        raw = path.read_bytes()
        if hashlib.sha256(raw).hexdigest() != entry["sha256"]:
            errors.append(f"SHA-256 mismatch: {rel}")
        git_blob = hashlib.sha1(f"blob {len(raw)}\0".encode() + raw).hexdigest()
        if git_blob != entry["source_git_blob"]:
            errors.append(f"Original Git blob mismatch: {rel}")
        if len(raw) != entry["size"]:
            errors.append(f"Size mismatch: {rel}")
        executable = bool(path.stat().st_mode & 0o111)
        if executable != (entry["source_git_mode"] == "100755"):
            errors.append(f"Executable mode mismatch: {rel}")
        if path.suffix == ".py":
            try:
                with tokenize.open(path) as handle:
                    ast.parse(handle.read(), filename=rel)
                counts["python_syntax"] += 1
            except (SyntaxError, UnicodeError) as exc:
                errors.append(f"Python syntax: {rel}: {exc}")
        elif path.suffix == ".sh":
            result = subprocess.run(["bash", "-n", str(path)], capture_output=True, text=True)
            if result.returncode:
                errors.append(f"Shell syntax: {rel}: {result.stderr.strip()}")
            counts["shell_syntax"] += 1

    # Anything added to a source collection must be accounted for, except its docs
    # and non-source Python bytecode generated by local verification.
    for collection in ("Experiments", "Benchmarks"):
        for path in (root / collection).rglob("*"):
            if not path.is_file() or "__pycache__" in path.parts:
                continue
            rel = path.relative_to(root).as_posix()
            if rel not in moved_paths and path.name != "README.md":
                errors.append(f"Unrecorded archive file: {rel}")

    if source is not None:
        result = subprocess.run(
            ["git", "ls-tree", "-rz", "--full-tree", manifest["source_commit"]],
            cwd=source, capture_output=True, check=True,
        )
        tree = {}
        for item in result.stdout.split(b"\0"):
            if not item:
                continue
            metadata, path = item.split(b"\t", 1)
            mode, kind, blob = metadata.decode().split()
            tree[path.decode()] = (mode, kind, blob)
        if set(tree) != set(source_paths):
            errors.append("Manifest does not cover the complete pinned source tree")
        for entry in entries:
            expected = (entry["source_git_mode"], "blob", entry["source_git_blob"])
            if tree.get(entry["source_path"]) != expected:
                errors.append(f"Pinned source mismatch: {entry['source_path']}")
        counts["pinned_source_entries"] = len(tree)

    # Check repository documentation links, including percent-encoded paths.
    for path in root.rglob("*.md"):
        if ".git" in path.parts or ".venv" in path.parts:
            continue
        doc = path.read_text(encoding="utf-8")
        if path.name == "README.md" and not re.match(r"# \d{4}-\d{2}-\d{2} · .+ — .+", doc):
            errors.append(f"README title format: {path.relative_to(root)}")
        doc = re.sub(r"```.*?```", "", doc, flags=re.DOTALL)
        for target in re.findall(r"\]\(([^\s)]+)\)", doc):
            target = target.strip("<>")
            parsed = urlsplit(target)
            if parsed.scheme or parsed.netloc or target.startswith("#"):
                continue
            resolved = path.parent / unquote(parsed.path)
            if not resolved.exists():
                errors.append(f"Broken link in {path.relative_to(root)}: {target}")
            counts["local_document_links"] += 1

    return {
        "source_commit": manifest["source_commit"],
        "counts": dict(sorted(counts.items())),
        "errors": errors,
        "model_initialization": "not_run_missing_research_environment",
        "training": "not_run",
        "dataset_download": "not_run",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, help="COD checkout containing the pinned original commit")
    parser.add_argument("--json", type=Path, help="Optional verification report path")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    result = check(root, args.source.resolve() if args.source else None)
    output = json.dumps(result, ensure_ascii=False, indent=2) + "\n"
    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        args.json.write_text(output, encoding="utf-8")
    print(output, end="")
    sys.exit(bool(result["errors"]))


if __name__ == "__main__":
    main()
